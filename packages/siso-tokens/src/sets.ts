export function sisoTokenVars(id: string, theme: SisoTheme): CSSProperties {
 const set = sisoTokenSets.find(s => s.id === id) ?? sisoTokenSets[0]
 const v = { ...set[theme] }
 const aliases: Record<string,string> = { "--siso-background":"--background", "--siso-panel":"--card", "--siso-raised":"--popover", "--siso-foreground":"--foreground", "--siso-muted":"--muted-foreground", "--siso-line":"--border", "--siso-accent":"--primary", "--siso-accent-foreground":"--primary-foreground", "--siso-chrome":"--sidebar", "--siso-ring":"--ring" }
 for (const [to,from] of Object.entries(aliases)) if (v[from]) v[to] = v[from]!
 return { ...v, colorScheme: theme } as CSSProperties
}
export function setSisoTokenSet(element: HTMLElement, id: string, theme: SisoTheme): void {
 element.dataset.sisoTokenSet=id
 element.dataset.sisoTheme=theme
 element.dataset.theme=theme
 element.classList.toggle("dark", theme === "dark")
 element.classList.toggle("light", theme === "light")
 for (const [key,value] of Object.entries(sisoTokenVars(id,theme))) if (key.startsWith("--")) element.style.setProperty(key,String(value))
}
